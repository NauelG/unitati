import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, resolve, sep } from 'node:path';

/**
 * Where attachment bytes live, behind the smallest interface that works.
 *
 * The product is self-hosted, so the default is the local filesystem: asking a
 * six-person team to run object storage to view a screenshot is asking them to
 * run infrastructure. The interface makes MinIO a new implementation, not a
 * rewrite, and lets the integration tests use an in-memory one.
 *
 * Keys are opaque to callers. The database row holds the key; the metadata
 * (filename, type, size) lives there and never in the storage.
 */
export interface Storage {
	put(key: string, data: Uint8Array): Promise<void>;
	/** `null` when the key is unknown, never an exception. */
	get(key: string): Promise<Uint8Array | null>;
	delete(key: string): Promise<void>;
}

export class LocalStorage implements Storage {
	readonly #root: string;

	constructor(root: string) {
		this.#root = resolve(root);
	}

	/**
	 * Keys are generated by the server, never taken from a request, but a path
	 * built from a string is a path-traversal bug waiting for the day that
	 * stops being true. The resolved path must stay inside the root.
	 */
	#pathOf(key: string): string {
		const path = resolve(this.#root, key);
		if (path !== this.#root && !path.startsWith(this.#root + sep)) {
			throw new Error(`Storage key escapes the uploads directory: ${key}`);
		}
		return path;
	}

	async put(key: string, data: Uint8Array): Promise<void> {
		const path = this.#pathOf(key);
		await mkdir(dirname(path), { recursive: true });
		await writeFile(path, data);
	}

	async get(key: string): Promise<Uint8Array | null> {
		try {
			return new Uint8Array(await readFile(this.#pathOf(key)));
		} catch (error) {
			if ((error as NodeJS.ErrnoException).code === 'ENOENT') return null;
			throw error;
		}
	}

	async delete(key: string): Promise<void> {
		await rm(this.#pathOf(key), { force: true });
	}
}

export class InMemoryStorage implements Storage {
	readonly #files = new Map<string, Uint8Array>();

	async put(key: string, data: Uint8Array): Promise<void> {
		this.#files.set(key, data);
	}

	async get(key: string): Promise<Uint8Array | null> {
		return this.#files.get(key) ?? null;
	}

	async delete(key: string): Promise<void> {
		this.#files.delete(key);
	}
}
