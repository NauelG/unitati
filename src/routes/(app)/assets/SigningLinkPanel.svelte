<script lang="ts">
	import Button from '#lib/components/unitati/Button.svelte';
	import Dialog from '#lib/components/unitati/Dialog.svelte';
	import { m } from '#lib/paraglide/messages.js';

	interface Props {
		link: string;
		qrSvg: string;
	}
	let { link, qrSvg }: Props = $props();
	let copied = $state(false);
	let qrOpen = $state(false);

	async function copy() {
		await navigator.clipboard.writeText(link);
		copied = true;
	}
</script>

<label class="block space-y-[var(--space-1)] text-sm">
	<span>{m.deliver_link_label()}</span>
	<input
		readonly
		value={link}
		class="w-full rounded border border-[var(--border)] bg-[var(--surface-2)] p-2 font-mono text-xs"
		onfocus={(event) => event.currentTarget.select()}
	/>
</label>
<p class="text-sm text-[var(--ink-muted)]">{m.deliver_link_once()}</p>
<div class="flex flex-wrap gap-[var(--space-2)]">
	<Button type="button" variant="secondary" onclick={copy}>
		{copied ? m.deliver_copied() : m.deliver_copy()}
	</Button>
	<Button type="button" variant="secondary" onclick={() => (qrOpen = true)}>
		{m.signing_link_show_qr()}
	</Button>
</div>

<Dialog
	open={qrOpen}
	onOpenChange={(next) => (qrOpen = next)}
	title={m.signing_link_qr_title()}
	class="top-0 left-0 h-dvh max-h-dvh w-full max-w-[100dvw] translate-x-0 translate-y-0 rounded-none"
>
	<div
		class="flex min-h-[calc(100dvh-8rem)] flex-col items-center justify-center gap-[var(--space-6)] text-center"
	>
		<p class="max-w-[28rem] text-sm text-[var(--ink-muted)]">{m.signing_link_qr_hint()}</p>
		<div
			role="img"
			aria-label={m.signing_link_qr_alt()}
			class="aspect-square w-[min(80vw,65dvh,560px)] bg-white [&>svg]:size-full"
		>
			<!-- eslint-disable-next-line svelte/no-at-html-tags -- generated by qrcode from the signing URL on the server -->
			{@html qrSvg}
		</div>
		<Button type="button" onclick={() => (qrOpen = false)}>{m.deliver_close()}</Button>
	</div>
</Dialog>
